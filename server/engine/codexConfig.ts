// config.toml for the box's Codex (CODEX_HOME = $VC_STATE_DIR/codex-home),
// regenerated before every app-server start so a hand (or agent) edit cannot
// persist.
//
// Sandbox: Codex refuses a deny entry on `danger-full-access` ("cannot extend
// unsupported built-in profile"), and under it the key store is plainly
// readable. So the agent runs under the custom profile `vc` instead: the whole
// filesystem readable, $HOME and /tmp writable, network on, and DENY on the key
// store, the phone token / VAPID / push-subscription dirs, the user's runtime
// dir (/run/user/<uid>: the systemd and D-Bus sockets — `systemd-run --user`
// from the agent's shell otherwise escapes the sandbox and reads the key store,
// measured) and tmux's socket dir. The server's own state and ~/.config are
// read-only so the agent cannot rewrite what the next start reads. Long jobs
// that must outlive a turn go through the StartJob tool: the server launches
// them with `systemd-run --user` wrapped in `codex sandbox` under this same
// profile, so they survive turns and restarts and still cannot read the keys.
import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { codexLimits } from "./catalog";

export type CodexConfigInput = {
  home: string;
  baseUrl: string;
  model: string;
  /** Paths the agent must not read at all. */
  deny: string[];
  /** Paths the agent may read but not write. */
  readOnly: string[];
  /** Writable roots. */
  write: string[];
};

const q = (s: string) => JSON.stringify(s);

/** Features off: no plugin marketplace clone, no apps/browser/computer use,
 * no sleep tool (waiting is ScheduleWake), no image generation. */
const FEATURES_OFF = [
  "plugins",
  "apps",
  "remote_plugin",
  "plugin_sharing",
  "browser_use",
  "browser_use_external",
  "computer_use",
  "in_app_browser",
  "image_generation",
  "sleep_tool",
  "goals",
  "tool_suggest",
  "skill_mcp_dependency_install",
  "realtime_conversation",
  "daemon_auto_start",
  // multi_agent sends a Responses `namespace` tool (multi_agent_v1) on every
  // non-OpenAI request; some OpenRouter endpoints reject that type (Codex
  // #32318). Off, the request carries only plain function tools.
  "multi_agent",
  "multi_agent_v2",
];

export function renderCodexConfig(c: CodexConfigInput): string {
  const lim = codexLimits(c.model);
  const linux = process.platform === "linux";
  const lines: string[] = [
    "# Generated by vault-chat-server at every start. Edits are overwritten.",
    `model = ${q(c.model)}`,
    `model_provider = "openrouter"`,
    `approval_policy = "never"`,
    `model_context_window = ${lim.model_context_window}`,
    `model_auto_compact_token_limit = ${lim.model_auto_compact_token_limit}`,
    `web_search = "disabled"`,
  ];
  if (linux) lines.push(`default_permissions = "vc"`);
  else lines.push(`sandbox_mode = "danger-full-access"  # no bubblewrap off Linux (dev only)`);
  lines.push(
    "",
    "[shell_environment_policy]",
    `exclude = ["OPENROUTER_*", "VC_*", "*_API_KEY"]`,
    "",
    "[model_providers.openrouter]",
    `name = "OpenRouter"`,
    `base_url = ${q(c.baseUrl)}`,
    `env_key = "OPENROUTER_API_KEY"`,
    `wire_api = "responses"`,
    "",
    "[features]",
    ...FEATURES_OFF.map((f) => `${f} = false`),
  );
  if (linux) {
    lines.push("", "[permissions.vc.filesystem]", `":root" = "read"`);
    // One entry per path; the strictest wins (deny > read > write).
    const access = new Map<string, string>();
    for (const p of c.write) access.set(p, "write");
    for (const p of c.readOnly) access.set(p, "read");
    for (const p of c.deny) access.set(p, "deny");
    for (const [p, a] of access) lines.push(`${q(p)} = "${a}"`);
    lines.push("", "[permissions.vc.network]", "enabled = true");
  }
  return lines.join("\n") + "\n";
}

export function writeCodexConfig(c: CodexConfigInput): string {
  mkdirSync(c.home, { recursive: true });
  const path = join(c.home, "config.toml");
  writeFileSync(path, renderCodexConfig(c));
  return path;
}
