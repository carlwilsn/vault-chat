// Regenerate src/defaultPromptHistory.ts — the set of line-ending-normalized
// sha256 hashes of EVERY version of each bundled default prompt that has ever
// shipped (walked from this repo's git history, plus the current working tree).
//
// Why: the app seeds each vault's `.vault-chat/agent/<name>` from the bundled
// default ONCE and never clobbers it, so a vault seeded before a prompt improved
// keeps the stale copy. meta.ts's ensureAgentConfig uses this registry to tell a
// pristine-but-OLD default (safe to upgrade) from a user-customized file (never
// touch): if the vault file's normalized hash is in here, it's an unmodified
// default we shipped, so it can be refreshed to the current bundle.
//
// Run after changing anything in src-tauri/defaults/*.md:
//   node scripts/gen-default-hashes.mjs
//
// The normalization here MUST match normalizedPromptHash() in src/meta.ts.
import { execSync } from "node:child_process";
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";

// The agent-config names map 1:1 to defaults/<file>; keep in sync with the
// ensureAgentConfig calls in meta.ts.
const FILES = ["system.md", "voice.md", "supervisor.md", "assistant.md", "ask.md"];
const DEFAULTS_DIR = "src-tauri/defaults";

// Canonical normalization: CRLF/CR → LF, strip trailing whitespace, single
// trailing newline. Identical to src/meta.ts so a file written on Windows
// (CRLF) hashes the same as the LF-seeded original.
function normalize(text) {
  return text.replace(/\r\n/g, "\n").replace(/\r/g, "\n").replace(/\s+$/, "") + "\n";
}
function hash(text) {
  return createHash("sha256").update(normalize(text), "utf8").digest("hex");
}

const registry = {};
for (const file of FILES) {
  const path = `${DEFAULTS_DIR}/${file}`;
  const hashes = new Set();
  // Every committed version across all refs.
  let commits = [];
  try {
    commits = execSync(`git log --all --format=%H -- "${path}"`, { encoding: "utf8" })
      .split("\n")
      .filter(Boolean);
  } catch {
    /* file may be new / untracked — fall through to working tree */
  }
  for (const c of commits) {
    try {
      const blob = execSync(`git show ${c}:${path}`, { encoding: "utf8", maxBuffer: 1 << 24 });
      hashes.add(hash(blob));
    } catch {
      /* file didn't exist at that commit */
    }
  }
  // The current working-tree version (covers an as-yet-uncommitted default).
  try {
    hashes.add(hash(readFileSync(path, "utf8")));
  } catch {
    /* no working-tree file */
  }
  registry[file] = [...hashes].sort();
}

const banner =
  "// AUTO-GENERATED by scripts/gen-default-hashes.mjs — do not edit by hand.\n" +
  "// Normalized (LF, trailing-trimmed) sha256 of every shipped version of each\n" +
  "// bundled default prompt. Used by meta.ts to upgrade pristine old defaults.\n" +
  "// Regenerate after editing any src-tauri/defaults/*.md.\n\n";
const body =
  "export const DEFAULT_PROMPT_HISTORY: Record<string, readonly string[]> = " +
  JSON.stringify(registry, null, 2) +
  " as const;\n";

writeFileSync("src/defaultPromptHistory.ts", banner + body);
const counts = Object.entries(registry).map(([k, v]) => `${k}=${v.length}`).join(" ");
console.log("wrote src/defaultPromptHistory.ts —", counts);
